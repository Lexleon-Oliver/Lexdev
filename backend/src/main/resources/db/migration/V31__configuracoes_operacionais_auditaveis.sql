-- Override operacional fechado: não permite criar/alterar flags fiscais, JWT ou licenciamento.
CREATE TABLE tb_operational_settings (
    setting_key VARCHAR(80) PRIMARY KEY,
    int_value INTEGER NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    updated_by VARCHAR(50) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_operational_setting_key CHECK (setting_key = 'ai.max-output-tokens'),
    CONSTRAINT ck_operational_setting_tokens CHECK (int_value BETWEEN 128 AND 2048)
);

CREATE TABLE tb_operational_setting_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key VARCHAR(80) NOT NULL,
    old_int_value INTEGER,
    new_int_value INTEGER,
    old_effective_value INTEGER NOT NULL,
    new_effective_value INTEGER NOT NULL,
    actor VARCHAR(50) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_operational_setting_audit_key CHECK (setting_key = 'ai.max-output-tokens'),
    CONSTRAINT ck_operational_setting_audit_old CHECK (old_int_value IS NULL OR old_int_value BETWEEN 128 AND 2048),
    CONSTRAINT ck_operational_setting_audit_new CHECK (new_int_value IS NULL OR new_int_value BETWEEN 128 AND 2048),
    CONSTRAINT ck_operational_setting_audit_effective CHECK (old_effective_value > 0 AND new_effective_value > 0)
);
CREATE INDEX ix_operational_setting_audit_key_time
    ON tb_operational_setting_audit (setting_key, occurred_at DESC);
